results.open = await p.evaluate(() => ({title:document.querySelector('h2')?.textContent, transforms:[...document.querySelectorAll('.will-change-transform')].map(e=>e.style.transform)}))
await p.getByRole('button', { name:'Close', exact:true }).click()
await p.waitForTimeout(5500)
results.closed = await p.evaluate(() => ({title:document.querySelector('h2')?.textContent, transforms:[...document.querySelectorAll('.will-change-transform')].map(e=>e.style.transform), opacity:[...document.querySelectorAll('[data-preview-mode="reel"]')].map(e=>e.parentElement.style.opacity)}))
await p.screenshot({path:'scratch/qa/baseline-close-race.png'})
await fs.writeFile('scratch/qa/baseline-races.json',JSON.stringify(results,null,2))
console.log(results)
