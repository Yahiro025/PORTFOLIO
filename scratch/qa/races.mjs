await p.evaluate(() => { window.openedContacts = []; window.open = url => { window.openedContacts.push(url); return null } })
for (const y of [497, 548, 601, 651]) { await p.mouse.click(700, y); await p.waitForTimeout(350) }
console.log('taps', await p.evaluate(() => window.openedContacts))
results.contact = await p.evaluate(() => ({taps:window.openedContacts,links:[...document.querySelectorAll('[role="dialog"] a')].map(e=>({text:e.textContent,href:e.href})),canvas:[...document.querySelectorAll('canvas')].map(e=>({width:e.width,height:e.height}))}))
await fs.writeFile('scratch/qa/baseline-races.json',JSON.stringify(results,null,2))
